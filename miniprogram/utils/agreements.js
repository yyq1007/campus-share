// 段落渲染约定：**加粗** 会被解析成 <text class="strong"> 段落
function parseBlocks (raw) {
  return raw
    .split('\n')
    .filter(s => s.trim() !== '')
    .map(line => {
      const t = line.trim()
      const m = t.match(/^\*\*(.+)\*\*$/)
      if (m) {
        return { type: 'h', text: m[1] }
      }
      return { type: 'p', text: t }
    })
}

